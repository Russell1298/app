def _results(header_summary: dict):
    h = HeaderScanResult(domain=DOMAIN, scanned_url="", scan_timestamp=TS, findings=[], information_leaks=[],
                         risk_score=0, risk_level="low", summary=header_summary)
    d = DNSScanResult(domain=DOMAIN, scan_timestamp=TS, records=[], findings=[], risk_score=40,
                      risk_level="high", summary={})
    s = SSLScanResult(domain=DOMAIN, port=443, scan_timestamp=TS, certificate=None, tls_versions=[],
                      findings=[], risk_score=40, risk_level="high", summary={})
    e = ExposureScanResult(domain=DOMAIN, scan_timestamp=TS, findings=[], risk_score=40,
                           risk_level="high", summary={})
    return h, d, s, e


def test_unverified_scanner_does_not_pull_the_score_down():
    h, d, s, e = _results({"verified": False, "error": "refused"})
    unseen = _weighted_score(h, d, s, e)

    # Treating the unseen headers as a perfect 0 would give this (the old behaviour).
    as_if_perfect = round(40 * (0.28 + 0.22 + 0.17))
    # Leaving them out should score as if headers matched the scanners we did see.
    h_matching = h.model_copy(update={"risk_score": 40, "summary": {}})
    as_if_matching = _weighted_score(h_matching, d, s, e)

    assert unseen > as_if_perfect
    assert unseen == as_if_matching


def test_score_unchanged_when_everything_is_verified():
    h, d, s, e = _results({})
    expected = round(40 * (0.28 + 0.22 + 0.17))
    assert _weighted_score(h, d, s, e) == expected


def test_unverified_scanners_are_named_in_the_report():
    h, d, s, e = _results({"verified": False, "error": "Cloudflare answered with a bot-protection page."})
    assert _unverified(headers=h, exposure=e) == {"headers": "Cloudflare answered with a bot-protection page."}
