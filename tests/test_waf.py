"""
Tests for WAF / bot-protection handling.

The failure these guard against: the scanner is served a challenge or block
page instead of the customer's site, grades that page, and the report tells the
customer their site lacks protections it actually has — or looks clean because
the real content was never seen.
"""
import asyncio
from unittest.mock import patch

import httpx
import pytest

from scanners import waf, exposure, headers, secrets, BROWSER_SCAN_HEADERS
from scanners.waf import Access
from reports.generator import _weighted_score, _unverified
from models.scan import (
    HeaderScanResult, DNSScanResult, SSLScanResult, ExposureScanResult,
)

DOMAIN = "example.test"
TS = "2026-09-22T00:00:00+00:00"

FULL_HEADERS = {
    "content-type": "text/html",
    "content-security-policy": "default-src 'self'",
    "strict-transport-security": "max-age=31536000",
    "x-frame-options": "SAMEORIGIN",
    "x-content-type-options": "nosniff",
    "referrer-policy": "no-referrer",
    "permissions-policy": "camera=()",
}

CF_CHALLENGE_200 = (
    "<!DOCTYPE html><html><head><title>Just a moment...</title></head><body>"
    "<script>window._cf_chl_opt={cvId:'3'};</script></body></html>"
)


def resp(status: int, headers: dict | None = None, text: str = "<html><body>ok</body></html>",
         url: str = f"https://{DOMAIN}/") -> httpx.Response:
    headers = {"content-type": "text/html", **(headers or {})}
    return httpx.Response(status, headers=headers, text=text, request=httpx.Request("GET", url))


def run(coro):
    return asyncio.run(coro)


# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("response, vendor", [
    (resp(403, {"cf-mitigated": "challenge"}), "Cloudflare"),
    (resp(200, text=CF_CHALLENGE_200), "Cloudflare"),               # a challenge served as HTTP 200
    (resp(405, {"x-amzn-waf-action": "captcha"}), "AWS WAF"),
    (resp(403, text="<p>Request unsuccessful. Incapsula incident ID: 123</p>"), "Imperva"),
    (resp(403, text="<a href='https://errors.edgesuite.net/18.1'>Reference</a>"), "Akamai"),
    (resp(403, text="<title>Sucuri WebSite Firewall - Access Denied</title>"), "Sucuri"),
    (resp(503, text="<p>Generated by Wordfence at Mon</p>"), "Wordfence"),
])
def test_vendor_challenge_pages_are_recognised(response, vendor):
    assert waf.waf_vendor(response) == vendor
    assert waf.block_reason(response) is not None


@pytest.mark.parametrize("text", [
    # Cloudflare injects this detection script into ordinary pages behind it.
    '<html><script src="/cdn-cgi/challenge-platform/h/b/scripts/jsd/main.js"></script><h1>Shop</h1></html>',
    # A single-page app shell is not a challenge, however little it contains.
    '<html><noscript>You need to enable JavaScript to run this app.</noscript><div id="root"></div></html>',
])
def test_ordinary_pages_behind_a_waf_are_not_mistaken_for_challenges(text):
    page = resp(200, text=text)
    assert waf.waf_vendor(page) is None
    assert waf.block_reason(page) is None


def test_plain_refusal_status_is_a_block_without_a_vendor():
    refused = resp(403, text="Forbidden")
    assert waf.waf_vendor(refused) is None
    assert "HTTP 403" in waf.block_reason(refused)


# ---------------------------------------------------------------------------
# Access probe
# ---------------------------------------------------------------------------

def _homepage(scanner, browser):
    async def fake(domain, request_headers):
        r = browser if request_headers["User-Agent"] == BROWSER_SCAN_HEADERS["User-Agent"] else scanner
        if isinstance(r, Exception):
            raise r
        return r
    return patch.object(waf, "_get_homepage", fake)


def test_challenge_to_scanner_is_retried_as_a_browser():
    with _homepage(resp(200, text=CF_CHALLENGE_200), resp(200, FULL_HEADERS)):
        access = run(waf.probe_access(DOMAIN))
    assert access.blocked is None
    assert access.client == "browser"
    assert access.request_headers["User-Agent"] == BROWSER_SCAN_HEADERS["User-Agent"]


def test_challenge_to_both_clients_is_reported_not_graded():
    with _homepage(resp(403, {"cf-mitigated": "challenge"}), resp(403, {"cf-mitigated": "challenge"})):
        access = run(waf.probe_access(DOMAIN))
    assert access.response is None
    assert "Cloudflare" in access.blocked


def test_a_block_reason_is_kept_over_a_later_network_error():
    with _homepage(resp(403, {"cf-mitigated": "challenge"}), httpx.ConnectTimeout("slow")):
        access = run(waf.probe_access(DOMAIN))
    assert "Cloudflare" in access.blocked


# ---------------------------------------------------------------------------
# Scanners never grade or claim anything from a refused scan
# ---------------------------------------------------------------------------

BLOCKED = Access(None, {"User-Agent": "x"}, "scanner", "Cloudflare answered with a bot-protection page (HTTP 403).")


class _NoNetwork:
    def __init__(self, *a, **k):
        raise AssertionError("a refused scan must not send further requests")


def test_headers_are_unverified_not_missing_when_refused():
    result = run(headers.scan_headers(DOMAIN, BLOCKED))
    assert result.findings == []
    assert result.summary["verified"] is False
    assert "Cloudflare" in result.summary["error"]


def test_exposure_sends_no_probes_when_refused():
    with patch.object(exposure.httpx, "AsyncClient", _NoNetwork):
        result = run(exposure.scan_exposure(DOMAIN, BLOCKED))
    assert result.findings == []
    assert result.summary["verified"] is False


def test_secrets_reads_nothing_when_refused():
    with patch.object(secrets.httpx, "AsyncClient", _NoNetwork):
        result = run(secrets.scan_secrets(DOMAIN, BLOCKED))
    assert result.files_scanned == 0
    assert result.summary["verified"] is False


def test_headers_graded_from_the_real_page_when_reached():
    access = Access(resp(200, FULL_HEADERS), dict(BROWSER_SCAN_HEADERS), "browser", None)
    result = run(headers.scan_headers(DOMAIN, access))
    assert sum(1 for f in result.findings if f.status == "missing") == 0
    assert result.summary["client"] == "browser"


# ---------------------------------------------------------------------------
# Exposure: a WAF 403 is not the site's configuration
# ---------------------------------------------------------------------------

class _OneResponseClient:
    def __init__(self, response):
        self._response = response

    async def get(self, url):
        return self._response


ENV_PROBE = next(p for p in exposure._PROBES if p["path"] == "/.env")


def test_waf_answer_to_a_probe_makes_no_claim_about_the_path():
    refused: list[str] = []
    finding = run(exposure._probe(_OneResponseClient(resp(403, {"cf-mitigated": "block"})),
                                  f"https://{DOMAIN}", ENV_PROBE, refused=refused))
    assert finding is None
    assert refused == ["/.env"]


def test_the_sites_own_403_is_still_reported_as_blocked():
    finding = run(exposure._probe(_OneResponseClient(resp(403, text="Forbidden")),
                                  f"https://{DOMAIN}", ENV_PROBE, refused=[]))
    assert finding is not None and finding.exposed is False and "blocked" in finding.label


